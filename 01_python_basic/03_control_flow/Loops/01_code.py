# 1. Simple for loop over a list
names = ["Rakesh", "Amit", "Pooja", "Vikram"]
for name in names:
    print(f"Hello, {name}!")

# 2. Iterating with range()
for i in range(1, 6):
    print(f"Count: {i}")

# 3. Simple while loop
counter = 3
while counter > 0:
    print(f"Countdown: {counter}")
    counter -= 1
print("Launch! 🚀")
